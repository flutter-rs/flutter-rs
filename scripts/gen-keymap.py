#!/usr/bin/env python3
"""Generate flutter-glfw/src/keymap.rs from the installed Flutter SDK.

The map translates a GLFW key code into the Flutter (physical USB HID,
logical) key pair expected by FlutterKeyEvent. Both tables are taken
verbatim from the SDK so they always match the engine being targeted:

  packages/flutter/lib/src/services/keyboard_maps.g.dart  (GLFW -> logical name)
  packages/flutter/lib/src/services/keyboard_key.g.dart   (name -> logical/physical)

Usage:
  scripts/gen-keymap.py [FLUTTER_ROOT] > flutter-glfw/src/keymap.rs
"""
import os
import re
import shutil
import subprocess
import sys


def flutter_root():
    if len(sys.argv) > 1:
        return sys.argv[1]
    if os.environ.get("FLUTTER_ROOT"):
        return os.environ["FLUTTER_ROOT"]
    flutter = shutil.which("flutter")
    if not flutter:
        sys.exit("flutter not found in PATH; pass FLUTTER_ROOT")
    return os.path.dirname(os.path.dirname(os.path.realpath(flutter)))


def main():
    svc = os.path.join(
        flutter_root(), "packages", "flutter", "lib", "src", "services"
    )
    key_file = open(os.path.join(svc, "keyboard_key.g.dart")).read()
    maps_file = open(os.path.join(svc, "keyboard_maps.g.dart")).read()

    def consts(kind):
        d = {}
        for m in re.finditer(
            r"static const %s (\w+) = %s\((0x[0-9a-fA-F]+)\);" % (kind, kind), key_file
        ):
            d[m.group(1)] = int(m.group(2), 16)
        return d

    logical = consts("LogicalKeyboardKey")
    physical = consts("PhysicalKeyboardKey")

    def parse_map(name):
        block = re.search(
            name + r" = <int, LogicalKeyboardKey>\{(.*?)\n\};", maps_file, re.S
        ).group(1)
        return [
            (int(m.group(1)), m.group(2))
            for m in re.finditer(r"(\d+):\s*LogicalKeyboardKey\.(\w+),", block)
        ]

    entries, skipped = {}, []
    for src in ("kGlfwToLogicalKey", "kGlfwNumpadMap"):
        for gk, lname in parse_map(src):
            lv, pv = logical.get(lname), physical.get(lname)
            if lv is None or pv is None:
                skipped.append((gk, lname))
                continue
            entries[gk] = (pv, lv)

    out = sys.stdout
    out.write("// @generated by scripts/gen-keymap.py from the Flutter SDK's\n")
    out.write("// keyboard_maps.g.dart / keyboard_key.g.dart. Do not edit by hand.\n//\n")
    out.write("// Maps a GLFW key code to a Flutter (physical USB HID, logical) key pair.\n")
    out.write("#[rustfmt::skip]\n")
    out.write("pub fn glfw_key_to_flutter(key: i32) -> Option<(u64, u64)> {\n")
    out.write("    let pair = match key {\n")
    for gk in sorted(entries):
        pv, lv = entries[gk]
        out.write(f"        {gk} => (0x{pv:08x}, 0x{lv:08x}),\n")
    out.write("        _ => return None,\n")
    out.write("    };\n    Some(pair)\n}\n")

    print(f"entries: {len(entries)}, skipped: {len(skipped)}", file=sys.stderr)


if __name__ == "__main__":
    main()
