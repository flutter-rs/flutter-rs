#!/usr/bin/env python3
"""Regenerate the GLFW -> Flutter key table in flutter-glfw/src/keymap.rs.

The table translates a GLFW key code into the Flutter (physical USB HID,
logical) key pair expected by FlutterKeyEvent. Both source tables are taken
verbatim from the installed SDK so they always match the engine being
targeted:

  packages/flutter/lib/src/services/keyboard_maps.g.dart  (GLFW -> logical name)
  packages/flutter/lib/src/services/keyboard_key.g.dart   (name -> logical/physical)

Only the generated prologue of keymap.rs is rewritten: everything after
`glfw_key_to_flutter` (the hand-maintained supplement and the tests) is spliced
back unchanged. The new file is written through a temporary file and renamed
into place, so a failure here can never leave keymap.rs empty -- which is what
the old `gen-keymap.py > keymap.rs` form did on any error.

Usage:
  scripts/gen-keymap.py [-o OUTPUT] [--check] [FLUTTER_ROOT]

  -o OUTPUT   file to rewrite; defaults to flutter-glfw/src/keymap.rs next to
              this script, and `-o -` prints the generated region to stdout
  --check     only report whether OUTPUT is up to date (exit 1 if it is not)
"""

import argparse
import os
import re
import shutil
import stat
import sys
import tempfile

# Where the generated region ends and the hand-maintained part begins.
TABLE_SIGNATURE = "pub fn glfw_key_to_flutter(key: i32) -> Option<(u64, u64)> {"

HEADER = """\
// The table in `glfw_key_to_flutter` is @generated by scripts/gen-keymap.py
// from the Flutter SDK's keyboard_maps.g.dart / keyboard_key.g.dart; do not
// edit it by hand. Everything below it — `glfw_key_to_flutter_extra` and the
// tests — is hand-maintained and has to be kept when the table is regenerated.
//
// Maps a GLFW key code to a Flutter (physical USB HID, logical) key pair.
#[rustfmt::skip]
"""

# The SDK tables this script scrapes, in the order they are merged.
SOURCE_MAPS = ("kGlfwToLogicalKey", "kGlfwNumpadMap")

# Key pairs that have been stable since Flutter introduced these tables, used
# as an independent check on the scrape: if the SDK ever disagrees we stop
# instead of quietly rewriting keymap.rs with different ids. The generated
# test module asserts the same values, so they are checked from both sides.
REFERENCE = {
    32: (0x0007002C, 0x00000020, "space"),
    65: (0x00070004, 0x00000061, "A"),
    256: (0x00070029, 0x10000001B, "escape"),
    257: (0x00070028, 0x10000000D, "enter"),
    340: (0x000700E1, 0x200000102, "left shift"),
}

# A scrape that produces far fewer entries than this has almost certainly hit
# an upstream rename rather than a real shrinking of the key table.
MIN_ENTRIES = 100


def repo_root():
    return os.path.dirname(os.path.dirname(os.path.realpath(__file__)))


def flutter_root(explicit):
    if explicit:
        return explicit
    if os.environ.get("FLUTTER_ROOT"):
        return os.environ["FLUTTER_ROOT"]
    flutter = shutil.which("flutter")
    if not flutter:
        sys.exit("flutter not found in PATH; pass FLUTTER_ROOT")
    return os.path.dirname(os.path.dirname(os.path.realpath(flutter)))


def read_source(svc, name):
    path = os.path.join(svc, name)
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except OSError as error:
        sys.exit(f"cannot read {path}: {error}\nis FLUTTER_ROOT really a Flutter SDK?")


def parse_consts(key_file, kind):
    """Collect `static const <kind> name = <kind>(0x...)` declarations."""
    pattern = r"static const %s (\w+) = %s\((0x[0-9a-fA-F]+)\);" % (kind, kind)
    found = {
        match.group(1): int(match.group(2), 16)
        for match in re.finditer(pattern, key_file)
    }
    if not found:
        sys.exit(f"no {kind} constants in keyboard_key.g.dart - upstream renamed them")
    return found


def parse_map(maps_file, name):
    """Collect the `<int, LogicalKeyboardKey>` entries of one SDK table."""
    block = re.search(name + r" = <int, LogicalKeyboardKey>\{(.*?)\n\};", maps_file, re.S)
    if block is None:
        sys.exit(f"{name} not found in keyboard_maps.g.dart - upstream renamed it")
    return [
        (int(match.group(1)), match.group(2))
        for match in re.finditer(
            r"(\d+):\s*LogicalKeyboardKey\.(\w+),", block.group(1)
        )
    ]


def collect(svc):
    key_file = read_source(svc, "keyboard_key.g.dart")
    maps_file = read_source(svc, "keyboard_maps.g.dart")

    logical = parse_consts(key_file, "LogicalKeyboardKey")
    physical = parse_consts(key_file, "PhysicalKeyboardKey")

    entries, skipped = {}, []
    for source in SOURCE_MAPS:
        for glfw_key, name in parse_map(maps_file, source):
            logical_id, physical_id = logical.get(name), physical.get(name)
            if logical_id is None or physical_id is None:
                skipped.append((glfw_key, name))
                continue
            entries[glfw_key] = (physical_id, logical_id)

    if len(entries) < MIN_ENTRIES:
        sys.exit(
            f"only {len(entries)} entries parsed (expected at least {MIN_ENTRIES}); "
            "the SDK's key tables have probably changed shape"
        )

    for glfw_key, (physical_id, logical_id, label) in REFERENCE.items():
        actual = entries.get(glfw_key)
        if actual != (physical_id, logical_id):
            sys.exit(
                f"the SDK maps GLFW {glfw_key} ({label}) to {actual}, "
                f"not the expected {(physical_id, logical_id)}; "
                "check the upstream change before regenerating"
            )

    return entries, skipped


def render_table(entries):
    lines = [HEADER, TABLE_SIGNATURE, "\n    let pair = match key {\n"]
    for glfw_key in sorted(entries):
        physical_id, logical_id = entries[glfw_key]
        lines.append(f"        {glfw_key} => (0x{physical_id:08x}, 0x{logical_id:08x}),\n")
    lines.append("        _ => return None,\n")
    lines.append("    };\n    Some(pair)\n}\n")
    return "".join(lines)


def render_tests():
    """The test module emitted for a from-scratch generation.

    Only used when keymap.rs does not exist yet; an existing file keeps its own
    (hand-extended) tests. The values come from REFERENCE, which `collect` has
    already checked against the SDK.
    """
    lines = [
        "\n#[cfg(test)]\nmod tests {\n    use super::glfw_key_to_flutter;\n",
        "\n    #[test]\n    fn known_keys_match_flutter_constants() {\n",
        "        // (GLFW key code, physical USB HID, Flutter logical) from the SDK.\n",
    ]
    for glfw_key, (physical_id, logical_id, label) in sorted(REFERENCE.items()):
        lines.append(
            f"        assert_eq!(glfw_key_to_flutter({glfw_key}), "
            f"Some(({physical_id:#011_x}, {logical_id:#011_x}))); // {label}\n"
        )
    lines.append("    }\n")
    lines.append(
        "\n    #[test]\n    fn unmapped_key_is_none() {\n"
        "        assert_eq!(glfw_key_to_flutter(-1), None);\n"
        "        assert_eq!(glfw_key_to_flutter(99999), None);\n"
        "    }\n}\n"
    )
    return "".join(lines)


def splice(existing, table):
    """Put `table` in front of the hand-maintained tail of `existing`."""
    start = existing.find(TABLE_SIGNATURE)
    if start < 0:
        sys.exit(
            f"{TABLE_SIGNATURE!r} not found in the output file, so the generated "
            "region cannot be told apart from the hand-written one"
        )
    end = existing.find("\n}\n", start)
    if end < 0:
        sys.exit("unterminated glfw_key_to_flutter in the output file")
    return table + existing[end + len("\n}\n") :]


def write_atomically(path, contents):
    """Write via a temporary file so a crash cannot truncate the target."""
    directory = os.path.dirname(os.path.abspath(path)) or "."

    # NamedTemporaryFile creates its file 0600, but the target is a checked-in
    # source file, so carry its mode over (0644 for one that does not exist
    # yet) instead of making keymap.rs owner-only on every regeneration.
    try:
        mode = stat.S_IMODE(os.stat(path).st_mode)
    except OSError:
        mode = 0o644

    handle = tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", dir=directory, prefix=".keymap-", suffix=".rs", delete=False
    )
    try:
        with handle:
            handle.write(contents)
        os.chmod(handle.name, mode)
        os.replace(handle.name, path)
    except BaseException:
        # Losing the temporary file is not worth masking whatever went wrong.
        try:
            os.unlink(handle.name)
        except OSError:
            pass
        raise


def main():
    parser = argparse.ArgumentParser(
        description="Regenerate the GLFW key table in flutter-glfw/src/keymap.rs."
    )
    parser.add_argument(
        "-o",
        "--output",
        default=os.path.join(repo_root(), "flutter-glfw", "src", "keymap.rs"),
        help="file to rewrite, or `-` for stdout",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="only report whether the output file is up to date",
    )
    parser.add_argument(
        "flutter_root", nargs="?", help="Flutter SDK root (default: $FLUTTER_ROOT or $PATH)"
    )
    args = parser.parse_args()

    svc = os.path.join(
        flutter_root(args.flutter_root), "packages", "flutter", "lib", "src", "services"
    )
    entries, skipped = collect(svc)
    table = render_table(entries)

    print(f"entries: {len(entries)}, skipped: {len(skipped)}", file=sys.stderr)

    if args.output == "-":
        if args.check:
            sys.exit("--check needs a real output file")
        sys.stdout.write(table)
        return

    try:
        with open(args.output, encoding="utf-8") as handle:
            existing = handle.read()
    except FileNotFoundError:
        existing = None

    wanted = table + render_tests() if existing is None else splice(existing, table)

    if args.check:
        if existing == wanted:
            print(f"{args.output} is up to date", file=sys.stderr)
            return
        sys.exit(f"{args.output} is out of date; re-run scripts/gen-keymap.py")

    if existing == wanted:
        print(f"{args.output} already up to date", file=sys.stderr)
        return

    write_atomically(args.output, wanted)
    print(f"wrote {args.output}", file=sys.stderr)


if __name__ == "__main__":
    main()
